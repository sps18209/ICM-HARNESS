# A fake `codex` binary. It ignores every CLI flag, reads the stage prompt from
# stdin, extracts the required artifact names the harness asked for, and emits a
# schema-valid structured result. This exercises the real subprocess/parse path
# without an authenticated Codex CLI.
FAKE_CODEX = """#!/usr/bin/env python3
import json, re, sys

prompt = sys.stdin.read()
match = re.search(r"Required artifact names: (.+)", prompt)
names = []
if match and match.group(1).strip() != "none":
    names = [n.strip() for n in match.group(1).split(",") if n.strip()]
artifacts = {}
for name in names:
    if name.endswith(".json"):
        artifacts[name] = json.dumps({"fake_codex": True, "artifact": name})
    else:
        artifacts[name] = "# " + name + "\\ngenerated by fake codex\\n"
print(json.dumps({
    "status": "pass",
    "summary": "fake codex completed",
    "artifacts": artifacts,
    "trigger_codes": [],
}))
"""

FAKE_CODEX_NONZERO = """#!/usr/bin/env python3
import sys
sys.stderr.write("boom: simulated agent failure\\n")
sys.exit(3)
"""

FAKE_CODEX_BAD_JSON = """#!/usr/bin/env python3
import sys
sys.stdin.read()
print("this is not json")
"""


def _write_executable(path: Path, body: str) -> Path:
    path.write_text(body, encoding="utf-8")
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return path


def _initialize(root: Path) -> None:
    (root / "0_Context_Wiki").mkdir(parents=True)
    (root / "2_Working_State").mkdir(parents=True)
    (root / "2_Working_State/CURRENT").write_text("NONE\n", encoding="utf-8")
    write_default_config(root / ".harness/config.toml")


def _in_place_config(root: Path):
    cfg = load_config(root)
    return dataclasses.replace(
        cfg, workspace=dataclasses.replace(cfg.workspace, strategy="in_place")
    )


def _build_profile(objective: str = "ship the feature") -> TaskProfile:
    return TaskProfile(
        objective,
        intent=TaskIntent.BUILD,
        specification_clarity=0.9,
        epistemic_uncertainty=0.1,
        stakes=0.4,
        reversibility=0.8,
        production_change_required=True,
    )


