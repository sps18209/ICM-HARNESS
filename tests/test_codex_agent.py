# --- CodexCLIStageAgent pure behaviour --------------------------------------


def test_available_reflects_executable_presence(tmp_path):
    fake = _write_executable(tmp_path / "codex", FAKE_CODEX)
    assert CodexCLIStageAgent(executable=str(fake)).available() is True
    assert CodexCLIStageAgent(executable=str(tmp_path / "missing")).available() is False


def test_schema_path_writes_expected_schema_and_is_idempotent(tmp_path):
    agent = CodexCLIStageAgent()
    path = agent._schema_path(tmp_path)
    assert path.exists()
    first = path.read_text(encoding="utf-8")
    assert '"status"' in first
    # required keys from the contract are present
    for key in RESULT_SCHEMA["required"]:
        assert key in first
    # A second call must not rewrite identical content (idempotent).
    mtime = path.stat().st_mtime_ns
    again = agent._schema_path(tmp_path)
    assert again.read_text(encoding="utf-8") == first
    assert again.stat().st_mtime_ns == mtime


def test_environment_filters_to_inherited_names(monkeypatch):
    monkeypatch.setenv("PATH", "/usr/bin")
    monkeypatch.setenv("CODEX_HOME", "/tmp/codex")
    monkeypatch.setenv("SECRET_TOKEN", "do-not-leak")
    agent = CodexCLIStageAgent(inherit_environment=("PATH", "CODEX_HOME"))
    env = agent._environment()
    assert env == {"PATH": "/usr/bin", "CODEX_HOME": "/tmp/codex"}
    assert "SECRET_TOKEN" not in env


# --- end-to-end through the application service ------------------------------


def test_real_agent_path_completes_a_build_round(tmp_path):
    _initialize(tmp_path)
    fake = _write_executable(tmp_path / "codex", FAKE_CODEX)
    app = HarnessApplication(
        tmp_path,
        config=_in_place_config(tmp_path),
        agent=CodexCLIStageAgent(executable=str(fake)),
    )
    created = app.create_round(_build_profile())
    result = anyio.run(app.run_round, created.round_id)

    assert result.status == "closed"
    names = [a.name for a in app.list_artifacts(result.round_id)]
    assert "execution-plan.md" in names
    assert "final-record.md" in names
    # The content came from the fake agent via the real subprocess path.
    _, content = app.read_artifact(
        next(a.id for a in app.list_artifacts(result.round_id) if a.name == "final-record.md")
    )
    assert "generated by fake codex" in content


def test_real_agent_failure_is_bounded_and_fails_closed(tmp_path):
    _initialize(tmp_path)
    fake = _write_executable(tmp_path / "codex", FAKE_CODEX_NONZERO)
    app = HarnessApplication(
        tmp_path,
        config=_in_place_config(tmp_path),
        agent=CodexCLIStageAgent(executable=str(fake)),
    )
    created = app.create_round(_build_profile())
    result = anyio.run(app.run_round, created.round_id)

    assert result.status == "failed"
    failures = [e for e in app.events(created.round_id) if e.kind == "stage_attempt_failed"]
    assert len(failures) == app.config.runtime.max_attempts
    assert "boom: simulated agent failure" in (result.last_error or "")


def test_real_agent_invalid_json_fails_closed(tmp_path):
    _initialize(tmp_path)
    fake = _write_executable(tmp_path / "codex", FAKE_CODEX_BAD_JSON)
    app = HarnessApplication(
        tmp_path,
        config=_in_place_config(tmp_path),
        agent=CodexCLIStageAgent(executable=str(fake)),
    )
    created = app.create_round(_build_profile())
    result = anyio.run(app.run_round, created.round_id)

    assert result.status == "failed"
    assert "invalid structured output" in (result.last_error or "")


def test_missing_executable_reports_a_clear_error(tmp_path):
    _initialize(tmp_path)
    app = HarnessApplication(
        tmp_path,
        config=_in_place_config(tmp_path),
        agent=CodexCLIStageAgent(executable=str(tmp_path / "nope")),
    )
    created = app.create_round(_build_profile())
    result = anyio.run(app.run_round, created.round_id)

    assert result.status == "failed"
    assert "agent executable not found" in (result.last_error or "")
    # Every failed attempt must have released its lease (regression guard).
    assert os.path.exists(tmp_path / ".harness")
