# A fake `claude` binary. It ignores every CLI flag, reads the stage prompt from
# stdin, extracts the artifact names the harness asked for, and emits a
# `claude -p --output-format json` ENVELOPE whose `result` field carries the
# stage-contract JSON as a string — exactly the shape the real CLI produces.
# This exercises the real subprocess + envelope-unwrap + parse path without an
# authenticated Claude CLI.
FAKE_CLAUDE = """#!/usr/bin/env python3
import json, re, sys

prompt = sys.stdin.read()
match = re.search(r"Required artifact names: (.+)", prompt)
names = []
if match and match.group(1).strip() != "none":
    names = [n.strip() for n in match.group(1).split(",") if n.strip()]
artifacts = {}
for name in names:
    if name.endswith(".json"):
        artifacts[name] = json.dumps({"fake_claude": True, "artifact": name})
    else:
        artifacts[name] = "# " + name + "\\ngenerated by fake claude\\n"
stage_result = json.dumps({
    "status": "pass",
    "summary": "fake claude completed",
    "artifacts": artifacts,
    "trigger_codes": [],
})
print(json.dumps({
    "type": "result",
    "subtype": "success",
    "is_error": False,
    "result": stage_result,
    "session_id": "fake",
    "total_cost_usd": 0.0,
}))
"""

# Same, but wraps the stage JSON in a Markdown code fence inside `result` — the
# common model slip the adapter must salvage.
FAKE_CLAUDE_FENCED = """#!/usr/bin/env python3
import json, re, sys

prompt = sys.stdin.read()
match = re.search(r"Required artifact names: (.+)", prompt)
names = []
if match and match.group(1).strip() != "none":
    names = [n.strip() for n in match.group(1).split(",") if n.strip()]
artifacts = {}
for n in names:
    if n.endswith(".json"):
        artifacts[n] = json.dumps({"fake_claude": True, "artifact": n})
    else:
        artifacts[n] = "# " + n + "\\nfenced\\n"
stage_result = json.dumps({
    "status": "pass", "summary": "fenced", "artifacts": artifacts, "trigger_codes": [],
})
print(json.dumps({
    "type": "result", "subtype": "success", "is_error": False,
    "result": "```json\\n" + stage_result + "\\n```",
}))
"""

# The CLI itself reports an error (auth failure, etc.): envelope is_error=true.
FAKE_CLAUDE_ERROR_ENVELOPE = """#!/usr/bin/env python3
import json, sys
sys.stdin.read()
print(json.dumps({
    "type": "result", "subtype": "error_during_execution", "is_error": True,
    "result": "simulated claude auth failure",
}))
"""

# Non-zero exit with a message on stderr.
FAKE_CLAUDE_NONZERO = """#!/usr/bin/env python3
import sys
sys.stderr.write("boom: simulated claude crash\\n")
sys.exit(2)
"""

# Valid envelope, but `result` is not JSON — off-contract model output.
FAKE_CLAUDE_BAD_STAGE_JSON = """#!/usr/bin/env python3
import json, sys
sys.stdin.read()
print(json.dumps({
    "type": "result", "subtype": "success", "is_error": False,
    "result": "I could not follow the schema, sorry.",
}))
"""

# Records the argv it was invoked with so a test can assert the read-only
# stage denied the write tools.
FAKE_CLAUDE_ARGV_ECHO = """#!/usr/bin/env python3
import json, sys
sys.stdin.read()
print(json.dumps({
    "type": "result", "subtype": "success", "is_error": False,
    "result": json.dumps({"status": "pass", "summary": " ".join(sys.argv[1:]),
                          "artifacts": {}, "trigger_codes": []}),
}))
"""


def _write_executable(path: Path, body: str) -> Path:
    path.write_text(body, encoding="utf-8")
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return path


def _initialize(root: Path) -> None:
    (root / "0_Context_Wiki").mkdir(parents=True)
    (root / "2_Working_State").mkdir(parents=True)
    (root / "2_Working_State/CURRENT").write_text("NONE\n", encoding="utf-8")
    write_default_config(root / ".harness/config.toml")


def _in_place_config(root: Path):
    cfg = load_config(root)
    return dataclasses.replace(
        cfg, workspace=dataclasses.replace(cfg.workspace, strategy="in_place")
    )


def _build_profile(objective: str = "ship the feature") -> TaskProfile:
    return TaskProfile(
        objective,
        intent=TaskIntent.BUILD,
        specification_clarity=0.9,
        epistemic_uncertainty=0.1,
        stakes=0.4,
        reversibility=0.8,
        production_change_required=True,
    )


