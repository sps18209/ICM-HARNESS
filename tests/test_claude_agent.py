def test_available_reflects_executable_presence(tmp_path):
    fake = _write_executable(tmp_path / "claude", FAKE_CLAUDE)
    assert ClaudeCLIStageAgent(executable=str(fake)).available() is True
    assert ClaudeCLIStageAgent(executable=str(tmp_path / "missing")).available() is False


def test_environment_forwards_auth_env_plus_inherited(monkeypatch):
    monkeypatch.setenv("PATH", "/usr/bin")
    monkeypatch.setenv("ANTHROPIC_BASE_URL", "https://example.invalid")
    monkeypatch.setenv("ANTHROPIC_API_KEY", "sk-test")
    monkeypatch.setenv("SECRET_TOKEN", "do-not-leak")
    agent = ClaudeCLIStageAgent(inherit_environment=("PATH",))
    env = agent._environment()
    assert env["PATH"] == "/usr/bin"
    # Anthropic auth env is forwarded even though it is not in inherit_environment.
    assert env["ANTHROPIC_BASE_URL"] == "https://example.invalid"
    assert env["ANTHROPIC_API_KEY"] == "sk-test"
    # Anything outside inherit_environment + the auth allowlist is filtered.
    assert "SECRET_TOKEN" not in env


def test_extract_stage_json_strips_fence_and_prose():
    agent = ClaudeCLIStageAgent()
    obj = '{"status": "pass"}'
    assert json.loads(agent._extract_stage_json(obj)) == {"status": "pass"}
    assert json.loads(agent._extract_stage_json("```json\n" + obj + "\n```")) == {"status": "pass"}
    assert json.loads(agent._extract_stage_json("here you go:\n" + obj)) == {"status": "pass"}


