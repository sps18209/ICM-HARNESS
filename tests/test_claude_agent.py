def test_readonly_stage_denies_write_tools(tmp_path):
    """A non-mutating stage must invoke claude with --disallowed-tools; a
    mutating one must not."""
    from icm_harness.agents.contracts import StageInvocation
    from icm_harness.kernel.contracts import ContextBundle, Mode, StageSpec

    agent = ClaudeCLIStageAgent(executable="claude")

    def _command_for(mutates: bool) -> list[str]:
        stage = StageSpec(mode=Mode.QUICK, name="y", mutates_workspace=mutates)
        inv = StageInvocation(
            round_id="r", profile=_build_profile(), stage=stage,
            context=ContextBundle(items=(), tier=0, used_tokens=0, budget_tokens=1),
            settings=None, workspace=tmp_path, artifact_dir=tmp_path,
            model="default", attempt=1, authorization=None, cancel_requested=lambda: False,
        )
        return agent._command(inv)

    read_only = _command_for(False)
    assert "--disallowed-tools" in read_only
    for tool in ("Edit", "Write", "MultiEdit", "NotebookEdit"):
        assert tool in read_only

    mutating = _command_for(True)
    assert "--disallowed-tools" not in mutating
