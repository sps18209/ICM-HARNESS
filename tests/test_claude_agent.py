def test_real_agent_path_completes_a_build_round(tmp_path):
    _initialize(tmp_path)
    fake = _write_executable(tmp_path / "claude", FAKE_CLAUDE)
    app = HarnessApplication(
        tmp_path,
        config=_in_place_config(tmp_path),
        agent=ClaudeCLIStageAgent(executable=str(fake)),
    )
    created = app.create_round(_build_profile())
    result = anyio.run(app.run_round, created.round_id)

    assert result.status == "closed"
    names = [a.name for a in app.list_artifacts(result.round_id)]
    assert "execution-plan.md" in names
    assert "final-record.md" in names
    _, content = app.read_artifact(
        next(a.id for a in app.list_artifacts(result.round_id) if a.name == "final-record.md")
    )
    assert "generated by fake claude" in content


